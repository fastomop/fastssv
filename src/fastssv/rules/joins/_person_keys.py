def key_domain(table: str, column: str) -> Optional[Key]:
    """The entity key a column holds: the referenced key for a foreign key, the column itself for a primary key,
    None for any other column. ``death.person_id`` is both; it holds person keys."""
    target = FOREIGN_KEYS.get((table, column))
    if target is not None:
        return target
    if PRIMARY_KEYS.get(table) == column:
        return table, column
    return None


